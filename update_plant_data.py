"""Regenerate plant_data.py from a PvZ2 OBB after a game update.

Usage:  python update_plant_data.py main.<version>.com.ea.game.pvz2_row.obb

Reads the "Packages" group of the OBB (PopCap RSB format) and extracts:
  PLANTS       every PlantType* with an IntegerID, minus HideInPlantViewers helpers
  LEVEL_CAP    PlantLevelStats LevelCap per plant
  MASTERY_CAP  PlantMasteryProperties LevelCap
  SHOP_ONLY    "Plant Unlock" store products with no gem price
"""
import collections
import mmap
import os
import re
import struct
import sys
import zlib

import pvz2_rton as rton

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'plant_data.py')


def packages_blob(obb):
    """Return the decompressed data part of the RSB's "Packages" RSG packet."""
    u = lambda b, o: struct.unpack_from('<I', b, o)[0]
    if obb[:4] != b'1bsr':
        sys.exit('Not a PvZ2 OBB (expected RSB magic "1bsr").')
    count, start, size = u(obb, 0x28), u(obb, 0x2C), u(obb, 0x30)
    for k in range(count):
        e = start + k * size
        if obb[e:e + 128].split(b'\0')[0] == b'Packages':
            off, length = u(obb, e + 128), u(obb, e + 132)
            break
    else:
        sys.exit('No "Packages" group in this OBB.')
    rsg = obb[off:off + length]
    assert rsg[:4] == b'pgsr', 'Packages group is not an RSG packet'
    flags, p0_off, p0_zsize = u(rsg, 0x10), u(rsg, 0x18), u(rsg, 0x1C)
    raw = rsg[p0_off:p0_off + p0_zsize]
    return zlib.decompress(raw) if flags & 2 else raw


def rton_objects(blob):
    """Yield every object from every RTON file packed in the blob."""
    for m in re.finditer(rb'RTON\x01\x00\x00\x00', blob):
        end = blob.find(b'DONE', m.start())
        try:
            root = rton.decode(blob[m.start():end + 4])
        except Exception:  # not every match is a whole file; skip the ones that don't parse
            continue
        for o in root.get('objects', []):
            if isinstance(o, dict) and isinstance(o.get('objdata'), dict):
                yield o['objclass'], o['objdata']


def extract(blob):
    plants, caps, mastery, shop = {}, {}, None, collections.defaultdict(set)
    for cls, d in rton_objects(blob):
        if cls.startswith('PlantType') and 'IntegerID' in d and not d.get('HideInPlantViewers'):
            plants[int(d['IntegerID'])] = str(d['TypeName'])
        elif cls == 'PlantLevelStats' and 'LevelCap' in d:
            caps[str(d['TypeName'])] = int(d['LevelCap'])
        elif cls == 'PlantMasteryProperties':
            mastery = int(d['LevelCap'])
        elif cls == 'StoreProductProps' and d.get('ObjectType') == 'plant':
            shop[str(d['ObjectItem'])].add(bool(d.get('PriceGems')))
    if not plants or not caps or mastery is None:
        sys.exit('Could not find plant tables in this OBB; the format may have changed.')
    by_name = {n: i for i, n in plants.items()}
    level_cap = {i: caps[n] for i, n in plants.items() if n in caps}  # missing -> DEFAULT_LEVEL_CAP
    shop_only = {by_name[n] for n, gem in shop.items() if n in by_name and True not in gem}
    return plants, level_cap, mastery, shop_only


def render(source, plants, level_cap, mastery, shop_only):
    default = collections.Counter(level_cap.values()).most_common(1)[0][0]
    overrides = {i: c for i, c in sorted(level_cap.items()) if c != default}

    def wrap(items, indent='    '):
        lines, line = [], indent
        for item in items:
            if len(line) + len(item) + 1 > 88:
                lines.append(line.rstrip())
                line = indent
            line += item + ' '
        lines.append(line.rstrip())
        return '\n'.join(lines)

    return f'''"""Plant tables for pvz2_unlock_plants.py. Generated by update_plant_data.py; do not edit.

Source: {source}
"""

PLANTS = {{
{wrap(f"{i}: {n!r}," for i, n in sorted(plants.items()))}
}}

# Shop plants with no gem price (cash and/or mints only).
SHOP_ONLY = {{
{wrap(f"{i}," for i in sorted(shop_only))}
}}

DEFAULT_LEVEL_CAP = {default}
LEVEL_CAP = {{
{wrap(f"{i}: {c}," for i, c in overrides.items())}
}}

MASTERY_CAP = {mastery}
'''


def main(path):
    with open(path, 'rb') as f, mmap.mmap(f.fileno(), 0, access=mmap.ACCESS_READ) as obb:
        plants, level_cap, mastery, shop_only = extract(packages_blob(obb))
    old = None
    if os.path.exists(OUT):
        old = {}
        exec(open(OUT, encoding='utf-8').read(), old)
    open(OUT, 'w', encoding='utf-8').write(
        render(os.path.basename(path), plants, level_cap, mastery, shop_only))
    print(f'{len(plants)} plants, {len(shop_only)} shop-only, mastery cap {mastery} -> {OUT}')
    if old:
        new = set(plants) - set(old['PLANTS'])
        print('New plants: ' + (', '.join(plants[i] for i in sorted(new)) or 'none'))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
